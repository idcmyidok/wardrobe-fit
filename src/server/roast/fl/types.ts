/** v가 min이면 0.6, full이면 1, min의 절반이면 0 */
export const ramp = (v: number, min: number, full: number): number => {
  if (v >= full) return 1;
  if (v >= min) return 0.6 + (0.4 * (v - min)) / Math.max(full - min, 1e-9);
  const lo = min * 0.5;
  return v > lo ? (0.6 * (v - lo)) / (min - lo) : 0;
};

